"""HTTP API: the targeted-control surface. Every phase action of every wing is reachable here.

Interactive docs at /docs (generated by FastAPI) list all routes.
"""

import os
from collections.abc import Callable
from typing import Any

from fastapi import APIRouter, FastAPI, Request
from fastapi.responses import JSONResponse, Response
from pydantic import ValidationError

from wings.api import dto
from wings.api.dto import (
    AdvanceChange,
    ActionRequest,
    ArtifactUpdate,
    AttachmentUpload,
    CreateProject,
    DiagramSettingsUpdate,
    FolderPaths,
    FolderPick,
    FolderUpdate,
    LLMSettingsUpdate,
    artifact_view,
    attachment_view,
    folder_view,
)
from wings.application.orchestrator import ActionFailedError, Orchestrator
from wings.application.ports import DiagramSettingsService, FolderPicker, LLMSettingsService
from wings.domain.errors import ConflictError, InvalidInputError, InvalidTransitionError, NotFoundError, PhaseLockedError
from wings.domain.phases import PhaseId
from wings.domain.project import slugify


# Raised whenever a response shape the frontend relies on changes; the UI warns when it differs.
# 2: trace with titles, phases with stale_cause (session s02). 3: attachments. 4: model settings. 5: diagram settings.
# 6: wings P3 to P7, next_actions in agent messages, test results in the trace. 7: running.
# 8: output folder (project.folder, /folder routes), design-check, data.speaker and data.drift on messages.
# 9: changes carried through the phases: GET /changes, POST /changes/{n}/advance, open_change in every project view.
API_VERSION = 9


def create_app(
    orch: Orchestrator,
    info: dict[str, Any] | Callable[[], dict[str, Any]],
    settings: LLMSettingsService | None = None,
    diagrams: DiagramSettingsService | None = None,
    picker: FolderPicker | None = None,
) -> FastAPI:
    app = FastAPI(title="Wings", version="0.1.0", description="AI-assisted software engineering environment")
    reg = orch.registry

    def error(status: int):
        async def handler(_: Request, exc: Exception) -> JSONResponse:
            detail: Any = exc.errors(include_url=False) if isinstance(exc, ValidationError) else str(exc)
            return JSONResponse(status_code=status, content={"detail": detail, "error": type(exc).__name__})

        return handler

    # Only input the developer can fix is 422; any other ValueError is a bug and stays a 500.
    app.add_exception_handler(NotFoundError, error(404))
    app.add_exception_handler(PhaseLockedError, error(409))
    app.add_exception_handler(InvalidTransitionError, error(409))
    app.add_exception_handler(ConflictError, error(409))
    app.add_exception_handler(InvalidInputError, error(422))
    app.add_exception_handler(ValidationError, error(422))
    app.add_exception_handler(ActionFailedError, error(502))

    api = APIRouter(prefix="/api")

    # Every project view says which change is being carried through (open_change). These three shadow
    # the dto functions of the same name, so each route below gets it without asking for it.
    def project_view(project: Any, registry: Any = None, running: dict[str, str] | None = None) -> dict[str, Any]:
        return dto.project_view(project, reg, running, open_change=orch.open_change(project.id))

    def with_change(body: dict[str, Any]) -> dict[str, Any]:
        found = orch.open_change(body["project"]["id"])
        body["project"]["open_change"] = found.model_dump(mode="json") if found else None
        return body

    def action_view(result: Any, registry: Any = None) -> dict[str, Any]:
        return with_change(dto.action_view(result, reg))

    def folder_import_view(result: Any, registry: Any = None) -> dict[str, Any]:
        return with_change(dto.folder_import_view(result, reg))

    @api.get("/health")
    def health() -> dict[str, Any]:
        return {"ok": True, "api_version": API_VERSION, "settings": settings is not None, "folder_picker": picker is not None, **(info() if callable(info) else info)}

    if settings is not None:

        @api.get("/settings")
        def get_settings() -> dict[str, Any]:
            return settings.view()

        @api.put("/settings/llm")
        def put_settings(body: LLMSettingsUpdate) -> dict[str, Any]:
            return settings.update(body.provider, body.api_key, body.models)

        @api.post("/settings/llm/test")
        def test_settings() -> dict[str, Any]:
            return settings.test()

    if diagrams is not None:

        @api.get("/settings/diagrams")
        def get_diagrams() -> dict[str, Any]:
            return diagrams.view()

        @api.put("/settings/diagrams")
        def put_diagrams(body: DiagramSettingsUpdate) -> dict[str, Any]:
            return diagrams.use_public_server(body.public_server)

        @api.post("/settings/diagrams/download")
        def download_plantuml() -> dict[str, Any]:
            return diagrams.download_jar()

    if picker is not None:

        @api.post("/system/pick-folder")
        def pick_folder(body: FolderPick | None = None) -> dict[str, Any]:
            """Open the folder dialog on this computer. A chosen folder that already has files is usually the
            parent the developer meant ("Projects"), so a subfolder named after the project is suggested."""
            req = body or FolderPick()
            chosen = picker.pick(req.start, "Choose a folder for the project's files")
            if chosen is None:
                return {"path": None, "empty": True, "suggested": None}
            port = orch.folder
            empty = port is None or port.is_empty(chosen)
            suggested = None
            if not empty and req.name.strip():
                candidate = os.path.join(chosen, slugify(req.name))
                if port is not None and port.is_empty(candidate):
                    suggested = candidate
            return {"path": chosen, "empty": empty, "suggested": suggested}

    @api.get("/system/default-folder")
    def default_folder(name: str = "") -> dict[str, Any]:
        """Where a project with this name would get its files if no folder is named. Creates nothing."""
        return {"path": orch.default_folder(name)}

    @api.get("/phases")
    def phases() -> list[dict[str, Any]]:
        return [m.describe() for m in reg.ordered()]

    @api.get("/projects")
    def projects() -> list[dict[str, Any]]:
        return [project_view(p, reg, orch.running(p.id)) for p in orch.list_projects()]

    @api.post("/projects", status_code=201)
    def create(body: CreateProject) -> dict[str, Any]:
        return project_view(orch.create_project(body.name, folder=body.folder), reg)

    @api.get("/projects/{pid}")
    def project(pid: str) -> dict[str, Any]:
        return project_view(orch.project(pid), reg, orch.running(pid))

    @api.get("/projects/{pid}/design-check")
    def design_check(pid: str) -> dict[str, Any]:
        check = orch.design_check(pid)
        return {"checked": False} if check is None else {"checked": True, **check.model_dump()}

    @api.get("/projects/{pid}/folder")
    def folder(pid: str) -> dict[str, Any]:
        return folder_view(orch.folder_status(pid))

    @api.put("/projects/{pid}/folder")
    def set_folder(pid: str, body: FolderUpdate) -> dict[str, Any]:
        return folder_view(orch.set_folder(pid, body.path)) | {"project": project_view(orch.project(pid), reg)}

    @api.post("/projects/{pid}/folder/import")
    def import_folder(pid: str, body: FolderPaths | None = None) -> dict[str, Any]:
        return folder_import_view(orch.import_folder_changes(pid, (body or FolderPaths()).paths), reg)

    @api.post("/projects/{pid}/folder/restore")
    def restore_folder(pid: str, body: FolderPaths) -> dict[str, Any]:
        return folder_view(orch.restore_folder_files(pid, body.paths or []))

    @api.post("/projects/{pid}/phases/{phase}/actions/{action}")
    def run(pid: str, phase: str, action: str, body: ActionRequest | None = None) -> dict[str, Any]:
        req = body or ActionRequest()
        return action_view(orch.run_action(pid, phase, action, req.input, attachments=req.attachments), reg)

    @api.get("/projects/{pid}/changes")
    def changes(pid: str) -> list[dict[str, Any]]:
        """Change requests, newest first: progress per phase, the next step, and which artifacts each one touched."""
        return [dto.change_view(c) for c in orch.changes(pid)]

    @api.post("/projects/{pid}/changes/{number}/advance")
    def advance_change(pid: str, number: int, body: AdvanceChange | None = None) -> dict[str, Any]:
        """Carry the change one phase further (one phase per call; the caller loops while stopped_reason is null)."""
        return with_change(dto.change_advance_view(orch.advance_change(pid, number, approve=(body or AdvanceChange()).approve), reg))

    @api.post("/projects/{pid}/phases/{phase}/approve")
    def approve(pid: str, phase: str) -> dict[str, Any]:
        return project_view(orch.approve(pid, phase), reg)

    @api.post("/projects/{pid}/phases/{phase}/reopen")
    def reopen(pid: str, phase: str) -> dict[str, Any]:
        return project_view(orch.reopen(pid, phase), reg)

    @api.get("/projects/{pid}/artifacts")
    def artifacts(pid: str, phase: str | None = None, include_retired: bool = False) -> list[dict[str, Any]]:
        orch.project(pid)
        ph = reg.get(phase).id if phase else None
        return [artifact_view(a) for a in orch.store.list_artifacts(pid, ph) if include_retired or not a.retired]

    @api.get("/projects/{pid}/artifacts/{aid}")
    def artifact(pid: str, aid: str) -> dict[str, Any]:
        return artifact_view(orch.store.get_artifact(pid, aid))

    @api.put("/projects/{pid}/artifacts/{aid}")
    def update(pid: str, aid: str, body: ArtifactUpdate) -> dict[str, Any]:
        saved, stale = orch.update_artifact(pid, aid, content=body.content, text=body.text)
        return {"artifact": artifact_view(saved), "stale": [s.value for s in stale], "project": project_view(orch.project(pid), reg)}

    @api.get("/projects/{pid}/artifacts/{aid}/history")
    def history(pid: str, aid: str) -> list[dict[str, Any]]:
        return [artifact_view(a) for a in orch.store.artifact_history(pid, aid)]

    @api.get("/projects/{pid}/artifacts/{aid}/svg")
    def svg(pid: str, aid: str) -> Response:
        source = orch.store.get_artifact(pid, aid).text or ""
        rendered = orch.renderer.render_svg(source)
        if rendered is None:
            return JSONResponse(status_code=503, content={"detail": "No PlantUML renderer configured or rendering failed."})
        return Response(content=rendered, media_type="image/svg+xml")

    @api.post("/projects/{pid}/attachments", status_code=201)
    def attach(pid: str, body: AttachmentUpload) -> dict[str, Any]:
        return attachment_view(orch.add_attachment(pid, body.name, body.media_type, body.data()))

    @api.get("/projects/{pid}/attachments")
    def attachments(pid: str) -> list[dict[str, Any]]:
        orch.project(pid)
        return [attachment_view(a) for a in orch.store.list_attachments(pid)]

    @api.get("/projects/{pid}/attachments/{aid}")
    def attachment(pid: str, aid: str) -> dict[str, Any]:
        return attachment_view(orch.store.get_attachment(pid, aid)) | {"text": orch.store.get_attachment(pid, aid).text}

    @api.get("/projects/{pid}/messages")
    def messages(pid: str, phase: str | None = None) -> list[dict[str, Any]]:
        orch.project(pid)
        ph: PhaseId | None = reg.get(phase).id if phase else None
        return [m.model_dump(mode="json") for m in orch.store.list_messages(pid, ph)]

    @api.get("/projects/{pid}/events")
    def events(pid: str, after: int = 0) -> list[dict[str, Any]]:
        orch.project(pid)
        return [e.model_dump(mode="json") for e in orch.store.list_events(pid, after)]

    @api.get("/projects/{pid}/trace")
    def trace(pid: str) -> dict[str, Any]:
        view = orch.trace_view(pid)
        return view.report.model_dump() | {
            "ratio": view.report.ratio,
            "requirements": [r.model_dump() for r in view.requirements],
            "artifacts": [a.model_dump() for a in view.artifacts],
            "results": view.results,
            "strength": view.strength,
        }

    app.include_router(api)
    return app
