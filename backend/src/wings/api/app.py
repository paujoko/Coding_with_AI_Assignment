"""HTTP API: the targeted-control surface. Every phase action of every wing is reachable here.

Interactive docs at /docs (generated by FastAPI) list all routes.
"""

from typing import Any

from fastapi import APIRouter, FastAPI, Request
from fastapi.responses import JSONResponse, Response
from pydantic import ValidationError

from wings.api.dto import ActionRequest, ArtifactUpdate, CreateProject, action_view, artifact_view, project_view
from wings.application.orchestrator import ActionFailedError, Orchestrator
from wings.domain.errors import ConflictError, InvalidInputError, InvalidTransitionError, NotFoundError, PhaseLockedError
from wings.domain.phases import PhaseId


# Raised whenever a response shape the frontend relies on changes; the UI warns when it differs.
# 2: trace with titles, phases with stale_cause (session s02).
API_VERSION = 2


def create_app(orch: Orchestrator, info: dict[str, Any]) -> FastAPI:
    app = FastAPI(title="Wings", version="0.1.0", description="AI-assisted software engineering environment")
    reg = orch.registry

    def error(status: int):
        async def handler(_: Request, exc: Exception) -> JSONResponse:
            detail: Any = exc.errors(include_url=False) if isinstance(exc, ValidationError) else str(exc)
            return JSONResponse(status_code=status, content={"detail": detail, "error": type(exc).__name__})

        return handler

    # Only input the developer can fix is 422; any other ValueError is a bug and stays a 500.
    app.add_exception_handler(NotFoundError, error(404))
    app.add_exception_handler(PhaseLockedError, error(409))
    app.add_exception_handler(InvalidTransitionError, error(409))
    app.add_exception_handler(ConflictError, error(409))
    app.add_exception_handler(InvalidInputError, error(422))
    app.add_exception_handler(ValidationError, error(422))
    app.add_exception_handler(ActionFailedError, error(502))

    api = APIRouter(prefix="/api")

    @api.get("/health")
    def health() -> dict[str, Any]:
        return {"ok": True, "api_version": API_VERSION, **info}

    @api.get("/phases")
    def phases() -> list[dict[str, Any]]:
        return [m.describe() for m in reg.ordered()]

    @api.get("/projects")
    def projects() -> list[dict[str, Any]]:
        return [project_view(p, reg) for p in orch.list_projects()]

    @api.post("/projects", status_code=201)
    def create(body: CreateProject) -> dict[str, Any]:
        return project_view(orch.create_project(body.name), reg)

    @api.get("/projects/{pid}")
    def project(pid: str) -> dict[str, Any]:
        return project_view(orch.project(pid), reg)

    @api.post("/projects/{pid}/phases/{phase}/actions/{action}")
    def run(pid: str, phase: str, action: str, body: ActionRequest | None = None) -> dict[str, Any]:
        return action_view(orch.run_action(pid, phase, action, (body or ActionRequest()).input), reg)

    @api.post("/projects/{pid}/phases/{phase}/approve")
    def approve(pid: str, phase: str) -> dict[str, Any]:
        return project_view(orch.approve(pid, phase), reg)

    @api.post("/projects/{pid}/phases/{phase}/reopen")
    def reopen(pid: str, phase: str) -> dict[str, Any]:
        return project_view(orch.reopen(pid, phase), reg)

    @api.get("/projects/{pid}/artifacts")
    def artifacts(pid: str, phase: str | None = None, include_retired: bool = False) -> list[dict[str, Any]]:
        orch.project(pid)
        ph = reg.get(phase).id if phase else None
        return [artifact_view(a) for a in orch.store.list_artifacts(pid, ph) if include_retired or not a.retired]

    @api.get("/projects/{pid}/artifacts/{aid}")
    def artifact(pid: str, aid: str) -> dict[str, Any]:
        return artifact_view(orch.store.get_artifact(pid, aid))

    @api.put("/projects/{pid}/artifacts/{aid}")
    def update(pid: str, aid: str, body: ArtifactUpdate) -> dict[str, Any]:
        saved, stale = orch.update_artifact(pid, aid, content=body.content, text=body.text)
        return {"artifact": artifact_view(saved), "stale": [s.value for s in stale], "project": project_view(orch.project(pid), reg)}

    @api.get("/projects/{pid}/artifacts/{aid}/history")
    def history(pid: str, aid: str) -> list[dict[str, Any]]:
        return [artifact_view(a) for a in orch.store.artifact_history(pid, aid)]

    @api.get("/projects/{pid}/artifacts/{aid}/svg")
    def svg(pid: str, aid: str) -> Response:
        source = orch.store.get_artifact(pid, aid).text or ""
        rendered = orch.renderer.render_svg(source)
        if rendered is None:
            return JSONResponse(status_code=503, content={"detail": "No PlantUML renderer configured or rendering failed."})
        return Response(content=rendered, media_type="image/svg+xml")

    @api.get("/projects/{pid}/messages")
    def messages(pid: str, phase: str | None = None) -> list[dict[str, Any]]:
        orch.project(pid)
        ph: PhaseId | None = reg.get(phase).id if phase else None
        return [m.model_dump(mode="json") for m in orch.store.list_messages(pid, ph)]

    @api.get("/projects/{pid}/events")
    def events(pid: str, after: int = 0) -> list[dict[str, Any]]:
        orch.project(pid)
        return [e.model_dump(mode="json") for e in orch.store.list_events(pid, after)]

    @api.get("/projects/{pid}/trace")
    def trace(pid: str) -> dict[str, Any]:
        view = orch.trace_view(pid)
        return view.report.model_dump() | {
            "ratio": view.report.ratio,
            "requirements": [r.model_dump() for r in view.requirements],
            "artifacts": [a.model_dump() for a in view.artifacts],
        }

    app.include_router(api)
    return app
